insert into public.disease_feature_profiles
(disease_id,nando_class_id,nando_source_id,class_source_url,source_version)
select d.id, c.class_id,c.nando_id,
'https://github.com/NanbyoData/nando/blob/master/data/nanbyo_class.json',
'NANDO historical source snapshot'
from classified c join public.disease_catalog d
 on d.mhlw_designation_number=c.designation_number
on conflict(disease_id) do update set nando_class_id=excluded.nando_class_id,
 nando_source_id=excluded.nando_source_id,class_source_url=excluded.class_source_url,
 source_version=excluded.source_version;

